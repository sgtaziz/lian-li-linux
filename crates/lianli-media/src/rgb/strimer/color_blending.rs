pub(super) fn rainbow_wave(geometry: Geometry, brightness: u8, reverse: bool) -> Vec<Frame> {
    let (gradient, mask, frame_count): (&[&str], &[&str], usize) = if geometry.lane_length == 22 {
        (&GRADIENT_22, &WAVE_MASK_22, 70)
    } else {
        (&GRADIENT_29, &WAVE_MASK_29, 90)
    };
    let mut output = Vec::with_capacity(frame_count);
    for step in 0..frame_count {
        let rotation = step * 2 % geometry.lane_length;
        let mut current = frame(geometry);
        for lane in 0..geometry.lanes {
            let mask_row = step + lane;
            for position in 0..geometry.lane_length {
                let source = if reverse {
                    position
                } else {
                    geometry.lane_length - position - 1
                };
                if mask_row < mask.len() && mask[mask_row].as_bytes()[source] == b'1' {
                    let gradient_position = (rotation + source) % geometry.lane_length;
                    let color = std::array::from_fn(|channel| {
                        let row = gradient[channel].as_bytes();
                        let offset = gradient_position * 2;
                        (hex(row[offset]) << 4) | hex(row[offset + 1])
                    });
                    current[lane * geometry.lane_length + position] = scale(color, brightness);
                }
            }
        }
        output.push(current);
    }
    output
}

pub(super) fn mixing(geometry: Geometry, colors: &[Color; 6], brightness: u8) -> Vec<Frame> {
    let table: &[&str] = if geometry.lane_length == 22 {
        &MIXING_22
    } else {
        &MIXING_29
    };
    let mut output = Vec::with_capacity(table.len());
    for row in table {
        let mut current = frame(geometry);
        for lane in 0..geometry.lanes {
            for (position, token) in row.bytes().enumerate() {
                let pixel = match token {
                    b'1' => scale(colors[0], brightness),
                    b'2' => scale(colors[1], brightness),
                    _ => [0; 3],
                };
                current[lane * geometry.lane_length + position] = pixel;
            }
        }
        output.push(current);
    }
    output
}

fn hex(value: u8) -> u8 {
    match value {
        b'0'..=b'9' => value - b'0',
        b'a'..=b'f' => value - b'a' + 10,
        _ => unreachable!(),
    }
}
