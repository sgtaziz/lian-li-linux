pub(super) fn render(effect: &RgbEffect, fans: usize, bottom: bool) -> Result<Vec<Vec<[u8; 3]>>> {
    ensure!((1..=4).contains(&fans), "TL fan count must be 1..=4");
    let table = TABLES[fans - 1];
    let scale = [0u16, 64, 128, 192, 255][effect.brightness.min(4) as usize];
    let mut frames = Vec::with_capacity(fans * 13);
    for shift in 0..fans * 13 {
        let mut out = vec![[0; 3]; fans * 26];
        for fan in 0..fans {
            for i in 0..13 {
                let position = fan * 13 + i;
                let source = if matches!(effect.direction, RgbDirection::CounterClockwise) {
                    position
                } else {
                    fans * 13 - position - 1
                };
                let t = table[(shift + source) % table.len()];
                let t = t.map(|v| ((u16::from(v) * scale) >> 8) as u8);
                out[fan * 26 + usize::from(bottom) * 13 + i] = t;
            }
        }
        frames.push(out);
    }
    Ok(frames)
}
