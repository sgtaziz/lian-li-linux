const SINGLE_SPARKS: &[(usize, usize)] = &[(9, 64), (48, 0), (70, 107)];

pub(super) fn render(effect: &RgbEffect, fans: usize) -> Vec<Vec<Color>> {
    let colors = palette(effect, Plane::Outer);
    let bright = brightness(effect);
    let led_count = fans * 24;
    let mut frames = vec![vec![[0; 3]; led_count]; 200];
    for &(led, start) in PULSE_STARTS {
        if led >= led_count {
            continue;
        }
        for (offset, intensity) in PULSE.into_iter().enumerate() {
            let frame = start + offset as i16;
            if (0..200).contains(&frame) {
                frames[frame as usize][led] = scale(
                    scale(colors[COLOR_INDEX[led]], u16::from(intensity)),
                    bright,
                );
            }
        }
    }
    for &(led, frame) in SINGLE_SPARKS {
        if led < led_count {
            frames[frame][led] = scale(scale(colors[COLOR_INDEX[led]], 5), bright);
        }
    }
    frames
}
